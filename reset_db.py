# ========================================================================================
# [모듈 이름] reset_db.py (또는 clean_db.py)
# [모듈 역할] 로컬에 저장된 SQLite 데이터베이스 파일(file_manager.db)을 찾아 물리적으로 삭제
#
# [이 모듈이 존재하는 이유]
# 1. 스키마 변경 시 빠른 초기화:
#    테이블 구조(컬럼 추가, UNIQUE 제약 조건 변경 등)를 수정했을 때,
#    기존 DB 파일을 삭제하고 새 테이블 구조로 깔끔하게 다시 시작할 수 있습니다.
# 2. 테스트 데이터 정기 세척:
#    개발/테스트 과정에서 쌓인 임시 데이터, 잘못 들어간 테스트 레코드를 한 번에 삭제하여
#    깨끗한 데이터베이스 상태를 보장합니다.
# 3. 안전한 삭제 처리:
#    존재하지 않는 파일을 삭제하려 할 때 발생하는 `FileNotFoundError` 예외를 방지하기 위해
#    파일 존재 여부를 사전에 검사합니다.
# ========================================================================================

import os  # 운영체제(Windows, macOS, Linux) 파일 시스템을 제어하는 파이썬 표준 라이브러리

# 삭제 대상이 될 SQLite 데이터베이스 파일 이름 지정
# (프로젝트 루트 디렉토리에 생성되는 DB 파일명을 작성합니다)
DB_FILE_PATH = "file_manager.db"


def reset_database(file_path: str = DB_FILE_PATH):
    """
    [데이터베이스 파일 삭제 및 초기화 함수]

    ■ 매개변수:
        file_path (str): 삭제할 SQLite 데이터베이스 파일 경로
    """
    print("🧹 [DB 초기화 작업 시작]...")

    # 1. os.path.exists(): 해당 경로에 파일이 실제로 존재하는지 확인
    if os.path.exists(file_path):
        try:
            # 2. os.remove(): 컴퓨터 디스크에서 해당 파일을 영구적으로 삭제
            os.remove(file_path)
            print(f"✅ [성공] 기존 SQLite DB 파일('{file_path}')을 깔끔하게 삭제했습니다!")
            print("💡 이제 프로그램을 다시 실행하면 새로운 DB 스키마가 정상 적용됩니다.")
        except PermissionError:
            # DB가 현재 다른 프로그램(GUI 실행 중, DB Browser 등)에서 열려있어 삭제 불가능한 경우
            print(f"❌ [오류] '{file_path}' 파일이 다른 프로그램에서 사용 중이어서 삭제할 수 없습니다.")
            print("   (실행 중인 메인 프로그램이나 DB 접속 툴을 끄고 다시 시도하세요.)")
    else:
        # 지정한 파일이 현재 작업 폴더에 없을 경우 출력되는 메시지
        print(f"🤔 삭제할 DB 파일('{file_path}')이 존재하지 않습니다. (이미 깨끗한 상태입니다)")


# =========================================================
# 단독 실행 블록 (스크립트 직접 실행 시에만 작동)
# =========================================================
if __name__ == "__main__":
    reset_database()